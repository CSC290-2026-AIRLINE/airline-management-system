function networkMealService(cabin: Cabin): 'complimentary' | 'paid' {
  if (cabin === 'economy') return 'paid'
  return 'complimentary'
}

export const mockRoutes: RouteSummary[] = ROUTE_DEFS.map((d) => {
  const cabinStatuses: RouteSummary['cabinStatuses'] = {
    economy: { state: d.custom?.economy ? 'custom' : 'inherited', mealService: d.custom?.economy ?? networkMealService('economy') },
    premium_economy: { state: 'inherited', mealService: networkMealService('premium_economy') },
    business: { state: d.custom?.business ? 'custom' : 'inherited', mealService: d.custom?.business ?? networkMealService('business') },
    first: { state: 'inherited', mealService: networkMealService('first') },
  }
  return {
    id: d.id,
    originAirport: d.origin,
    destinationAirport: d.destination,
    originCity: d.originCity,
    destinationCity: d.destinationCity,
    cabinStatuses,
  }
})

