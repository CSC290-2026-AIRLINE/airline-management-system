/**
 * Builds the next employee number for a newly created profile, e.g. `EMP-0092`.
 * A backend would assign this; deriving it here keeps the mock self-consistent.
 */
export function nextEmployeeNo(crew: readonly CrewMember[]): string {
  const highest = crew.reduce((max, member) => {
    const parsed = Number(member.employeeNo.replace(/\D/g, ''))
    return Number.isFinite(parsed) && parsed > max ? parsed : max
  }, 0)
  return `EMP-${String(highest + 1).padStart(4, '0')}`
}
